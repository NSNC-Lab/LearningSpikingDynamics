%% Local functions
function distance = cosine_distance_rows( ...
    first_vectors,second_vectors,sign_invariant)
    first_norm = sqrt(sum(first_vectors.^2,2));
    second_norm = sqrt(sum(second_vectors.^2,2));
    valid_first = isfinite(first_norm) & first_norm > eps;
    valid_second = isfinite(second_norm) & second_norm > eps;

    first_unit = nan(size(first_vectors));
    second_unit = nan(size(second_vectors));
    first_unit(valid_first,:) = ...
        first_vectors(valid_first,:)./first_norm(valid_first);
    second_unit(valid_second,:) = ...
        second_vectors(valid_second,:)./second_norm(valid_second);

    similarity = first_unit*second_unit.';
    similarity = max(-1,min(1,similarity));
    if sign_invariant
        similarity = abs(similarity);
    end
    distance = 1-similarity;
end

function [loading,explained_percent,eigenvalue_ratio] = ...
    calculate_pc1(batch_parameters,parameter_scale)
    n_parameters = size(batch_parameters,2);
    loading = nan(1,n_parameters);
    explained_percent = nan;
    eigenvalue_ratio = nan;

    valid_rows = all(isfinite(batch_parameters),2);
    scaled = batch_parameters(valid_rows,:)./parameter_scale;
    if size(scaled,1) < 2
        return
    end
    centered = scaled-mean(scaled,1);
    if norm(centered,'fro') <= eps
        return
    end

    [~,singular_values,coefficients] = svd(centered,'econ');
    eigenvalues = diag(singular_values).^2;
    if isempty(eigenvalues) || sum(eigenvalues) <= eps
        return
    end

    loading = coefficients(:,1).';
    explained_percent = 100*eigenvalues(1)/sum(eigenvalues);
    if numel(eigenvalues) == 1 || eigenvalues(2) <= eps
        eigenvalue_ratio = inf;
    else
        eigenvalue_ratio = eigenvalues(1)/eigenvalues(2);
    end
end

